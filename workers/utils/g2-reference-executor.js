// G2 exact-reference executor.
// This module is intentionally unregistered and does not know about remote D1/R2.
// Writes require two explicit caller guards and every insert must report changes=1.

const EXPLICIT_AUTHORIZATION = "G2_BACKFILL_EXPLICIT_AUTHORIZATION";
const PLAN_TYPE = "g2-exact-reference-plan-v1";
const GENERATED_BY = "g2-file-classifier";
const EXACT_INSERT_SQL = `INSERT INTO file_references
      (id, file_id, owner_type, owner_id, source, source_path)
      VALUES (?1, ?2, ?3, ?4, ?5, ?6)`;
const EXACT_ROLLBACK_SQL = `DELETE FROM file_references
      WHERE file_id = ?1 AND owner_type = ?2 AND owner_id = ?3
        AND source = ?4 AND source_path = ?5`;

function assertPlan(plan) {
  if (!plan || plan.planType !== PLAN_TYPE || plan.generatedBy !== GENERATED_BY) {
    throw new TypeError("plan must be generated by g2-file-classifier");
  }
  if (!Array.isArray(plan.up) || !Array.isArray(plan.rollback)) {
    throw new TypeError("plan must contain up and rollback arrays");
  }
  if (plan.up.length !== plan.rollback.length) {
    throw new TypeError("plan up/rollback lengths must match");
  }
  for (let index = 0; index < plan.up.length; index += 1) {
    const up = plan.up[index];
    const rollback = plan.rollback[index];
    if (up?.sql !== EXACT_INSERT_SQL || rollback?.sql !== EXACT_ROLLBACK_SQL) {
      throw new TypeError("plan contains an unsupported SQL statement");
    }
    if (rollback.executeOnlyWhenInsertChanges !== 1) {
      throw new TypeError("rollback guard missing for plan reference");
    }
    if (!Array.isArray(up.bindings) || up.bindings.length !== 6 || !Array.isArray(rollback.bindings) || rollback.bindings.length !== 5) {
      throw new TypeError("plan contains invalid parameter bindings");
    }
    if (!rollback.bindings.every((value, bindingIndex) => Object.is(value, up.bindings[bindingIndex + 1]))) {
      throw new TypeError("rollback bindings do not match up bindings");
    }
  }
}

function changesOf(result) {
  return Number(result?.meta?.changes ?? result?.changes ?? 0);
}

function assertGuard({ allowWrite, authorization }) {
  if (allowWrite !== true || authorization !== EXPLICIT_AUTHORIZATION) {
    throw new Error("exact reference writes require explicit authorization");
  }
}

async function runStatement(db, statement) {
  const result = await db.prepare(statement.sql).bind(...statement.bindings).run();
  return changesOf(result);
}

/**
 * Execute an exact-only plan. The default is safe: no SQL run occurs.
 * Rollback is attempted only for inserts that returned changes=1.
 */
export async function executeExactReferencePlan(
  db,
  plan,
  { allowWrite = false, authorization = null } = {},
) {
  assertPlan(plan);
  assertGuard({ allowWrite, authorization });

  const inserted = [];
  try {
    for (let index = 0; index < plan.up.length; index += 1) {
      const changes = await runStatement(db, plan.up[index]);
      if (changes !== 1) {
        throw new Error(`exact reference insert ${index} changed ${changes} rows`);
      }
      inserted.push(index);
    }
    return { inserted: inserted.length, rolledBack: 0 };
  } catch (error) {
    let rolledBack = 0;
    let rollbackError = null;
    for (const index of inserted.reverse()) {
      let changes;
      try {
        changes = await runStatement(db, plan.rollback[index]);
      } catch (rollbackFailure) {
        rollbackError = rollbackFailure;
        break;
      }
      if (changes !== 1) {
        rollbackError = new Error(`reference rollback ${index} changed ${changes} rows`);
        break;
      }
      rolledBack += 1;
    }
    const partial = rollbackError ? `; rollback failed after ${rolledBack} of ${inserted.length}` : `; rolled back ${rolledBack} inserted reference(s)`;
    if (error instanceof Error) {
      error.message = `${error.message}${partial}`;
      error.rollbackSummary = partial;
      if (rollbackError) error.rollbackError = rollbackError;
      throw error;
    }
    const fallback = new Error(`${String(error)}${partial}`, { cause: error });
    if (rollbackError) fallback.rollbackError = rollbackError;
    throw fallback;
  }
}

export { EXPLICIT_AUTHORIZATION, PLAN_TYPE };
