// @vitest-environment node
import { describe, expect, it } from "vitest";
import {
  executeExactReferencePlan,
  EXPLICIT_AUTHORIZATION,
} from "../g2-reference-executor.js";

const INSERT_SQL = `INSERT INTO file_references
      (id, file_id, owner_type, owner_id, source, source_path)
      VALUES (?1, ?2, ?3, ?4, ?5, ?6)`;
const ROLLBACK_SQL = `DELETE FROM file_references
      WHERE file_id = ?1 AND owner_type = ?2 AND owner_id = ?3
        AND source = ?4 AND source_path = ?5`;

function makeDb({ changes = [1], rollbackChanges = [1] } = {}) {
  const runs = [];
  return {
    runs,
    prepare(sql) {
      return {
        bind(...bindings) {
          return {
            async run() {
              runs.push({ sql, bindings });
              const value = sql === ROLLBACK_SQL ? rollbackChanges.shift() : changes.shift();
              return { meta: { changes: value ?? 0 } };
            },
          };
        },
      };
    },
  };
}

function plan() {
  return {
    planType: "g2-exact-reference-plan-v1",
    generatedBy: "g2-file-classifier",
    up: [
      { sql: INSERT_SQL, bindings: ["id-one", "one", "entry", "entry-one", "entry_content_json", "content.images[0].r2_key"] },
      { sql: INSERT_SQL, bindings: ["id-two", "two", "track", "track-two", "track_field", "r2_key"] },
    ],
    rollback: [
      { sql: ROLLBACK_SQL, bindings: ["one", "entry", "entry-one", "entry_content_json", "content.images[0].r2_key"], executeOnlyWhenInsertChanges: 1 },
      { sql: ROLLBACK_SQL, bindings: ["two", "track", "track-two", "track_field", "r2_key"], executeOnlyWhenInsertChanges: 1 },
    ],
  };
}

describe("G2 exact-reference executor", () => {
  it("rejects an unmarked plan before calling D1", async () => {
    const db = makeDb();
    await expect(executeExactReferencePlan(db, { up: [], rollback: [] }, {
      allowWrite: true,
      authorization: EXPLICIT_AUTHORIZATION,
    })).rejects.toThrow("generated by g2-file-classifier");
    expect(db.runs).toHaveLength(0);
  });

  it("rejects writes by default without calling D1", async () => {
    const db = makeDb();
    await expect(executeExactReferencePlan(db, plan())).rejects.toThrow("explicit authorization");
    expect(db.runs).toHaveLength(0);
  });

  it("requires the exact authorization marker", async () => {
    const db = makeDb();
    await expect(executeExactReferencePlan(db, plan(), {
      allowWrite: true,
      authorization: "wrong",
    })).rejects.toThrow("explicit authorization");
    expect(db.runs).toHaveLength(0);
  });

  it("rejects SQL outside the generated allowlist before any write", async () => {
    const db = makeDb();
    const malicious = plan();
    malicious.up[0].sql += "; DELETE FROM file_references";
    await expect(executeExactReferencePlan(db, malicious, {
      allowWrite: true,
      authorization: EXPLICIT_AUTHORIZATION,
    })).rejects.toThrow("unsupported SQL statement");
    expect(db.runs).toHaveLength(0);
  });

  it("rejects rollback bindings that do not match the insert", async () => {
    const db = makeDb();
    const mismatched = plan();
    mismatched.rollback[0].bindings[0] = "different-file";
    await expect(executeExactReferencePlan(db, mismatched, {
      allowWrite: true,
      authorization: EXPLICIT_AUTHORIZATION,
    })).rejects.toThrow("rollback bindings do not match");
    expect(db.runs).toHaveLength(0);
  });

  it("validates every plan statement before the first write", async () => {
    const db = makeDb();
    const invalidLater = plan();
    invalidLater.rollback[1].sql = `${ROLLBACK_SQL} OR 1=1`;
    await expect(executeExactReferencePlan(db, invalidLater, {
      allowWrite: true,
      authorization: EXPLICIT_AUTHORIZATION,
    })).rejects.toThrow("unsupported SQL statement");
    expect(db.runs).toHaveLength(0);
  });

  it("requires every insert to change exactly one row", async () => {
    const db = makeDb({ changes: [0] });
    await expect(executeExactReferencePlan(db, plan(), {
      allowWrite: true,
      authorization: EXPLICIT_AUTHORIZATION,
    })).rejects.toThrow("changed 0 rows");
    expect(db.runs).toHaveLength(1);
  });

  it("rolls back only confirmed inserts after a later failure", async () => {
    const db = makeDb({ changes: [1, 0], rollbackChanges: [1] });
    await expect(executeExactReferencePlan(db, plan(), {
      allowWrite: true,
      authorization: EXPLICIT_AUTHORIZATION,
    })).rejects.toThrow("rolled back 1 inserted reference(s)");
    expect(db.runs.map(run => run.sql)).toEqual([INSERT_SQL, INSERT_SQL, ROLLBACK_SQL]);
    expect(db.runs[2].bindings).toEqual(plan().rollback[0].bindings);
  });

  it("reports rollback failure without hiding the inconsistency", async () => {
    const db = makeDb({ changes: [1, 0], rollbackChanges: [0] });
    const error = await executeExactReferencePlan(db, plan(), {
      allowWrite: true,
      authorization: EXPLICIT_AUTHORIZATION,
    }).catch(caught => caught);
    expect(error.message).toContain("rollback failed after 0 of 1");
    expect(error.rollbackError).toBeDefined();
  });

  it("completes a fully successful plan without rollback", async () => {
    const db = makeDb({ changes: [1, 1] });
    await expect(executeExactReferencePlan(db, plan(), {
      allowWrite: true,
      authorization: EXPLICIT_AUTHORIZATION,
    })).resolves.toEqual({ inserted: 2, rolledBack: 0 });
    expect(db.runs).toHaveLength(2);
  });
});
